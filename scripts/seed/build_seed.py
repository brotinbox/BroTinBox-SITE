"""Build the Supabase seed migration from the menu workbook + data/*.json.

The workbook (Gramwise_30Day_Menu_and_Profit_Model.xlsx) is the source of truth
for dishes, nutrition, costs, the 30-day rotation and prices. Things it does not
have (images, fibre, customer descriptions, sides, drinks, plans, zones,
coupons, FAQs) come from data/*.json.

Usage:
  python3 -I scripts/seed/xlsx2csv.py <workbook.xlsx> <sheets_dir>
  python3 -I scripts/seed/build_seed.py <sheets_dir> <repo_dir> <out.sql>
"""
import csv, json, os, re, sys

sheets, repo, out = sys.argv[1:4]


def rows(name):
    with open(os.path.join(sheets, name), newline='') as f:
        return list(csv.reader(f))


def jdata(name):
    with open(os.path.join(repo, 'data', name)) as f:
        return json.load(f)


def q(v):
    if v is None or v == '':
        return 'null'
    return "'" + str(v).replace("'", "''") + "'"


def num(v, default='0'):
    v = str(v if v is not None else '').strip()
    return v if re.fullmatch(r'-?\d+(\.\d+)?', v) else default


def arr(items):
    items = [i for i in items if i]
    return 'array[' + ', '.join(q(i) for i in items) + ']::text[]' if items else "'{}'::text[]"


def portion_grams(portion, raw_qty):
    grams = [int(g) for g in re.findall(r'(\d+)\s*g\b', portion)]
    if '+' in portion and grams:
        return sum(grams)              # "40 g oats + 15 g moong dal" → 55
    if grams:
        return grams[0]                # "150 g cooked" → 150
    return int(float(raw_qty))         # "2 pieces" → raw weight


CATEGORY = {
    'Main (Non-Veg)': 'main', 'Main (Veg)': 'main',
    'Egg (Non-Veg)': 'protein_side', 'Curd (Veg)': 'protein_side',
    'Legume / Sprout': 'legume', 'Salad': 'salad', 'Carb': 'carb',
}
SALADS = [f'SL{i}' for i in range(1, 7)]
LEGUMES = [f'LG{i}' for i in range(1, 7)]
CARBS = [f'CB{i}' for i in range(1, 6)]

json_items = {c: i for g in jdata('menu-30day.json')['catalog'].values() for c, i in g.items()}

sql = [
    "-- =============================================================================",
    "-- BroTin Box · 0010 Seed: dishes, costs, 30-day menu, prices, add-ons, plans,",
    "-- zones, coupons, FAQs, cost model.",
    "-- Source of truth: Gramwise_30Day_Menu_and_Profit_Model.xlsx (Catalog, Menu NonVeg,",
    "-- Menu Veg, Settings). Images, fibre, customer descriptions, sides, drinks, plans,",
    "-- zones, coupons and FAQs come from data/*.json (not in the workbook).",
    "-- Generated by scripts/seed/build_seed.py. Idempotent (upserts by natural key).",
    "-- =============================================================================",
    "",
]

# --------------------------------------------------------------------------- Catalog
cat = rows('Catalog.csv')
H = {h: i for i, h in enumerate(cat[2])}
catalog = [r for r in cat[3:] if r and r[0]]
names = {r[H['ID']]: r[H['Item']] for r in catalog}
dishes = [r for r in catalog if not r[H['Category']].startswith('Dip')]
dips = [r for r in catalog if r[H['Category']].startswith('Dip')]

item_vals, cost_vals = [], []
for r in dishes:
    code = r[H['ID']]
    j = json_items.get(code, {})
    meta = json.dumps({
        'kitchen_notes': r[H['Notes and assumptions']],
        'raw_qty_g': float(r[H['Raw qty (g)']] or 0),
        'raw_price_per_kg': float(r[H['Raw price (₹/kg)']] or 0),
        'gas_lpg_g': float(r[H['Gas used (g LPG)']] or 0),
        'source': 'workbook:Catalog',
    }, ensure_ascii=False)
    item_vals.append(
        f"  ({q(code)}, '{CATEGORY[r[H['Category']]]}', {q(r[H['Item']])}, {q(j.get('description'))}, "
        f"{portion_grams(r[H['Portion']], r[H['Raw qty (g)']])}, {q(r[H['Portion']])}, "
        f"{num(r[H['Calories (kcal)']])}, {num(r[H['Protein (g)']])}, {num(r[H['Carbs (g)']])}, {num(r[H['Fat (g)']])}, "
        f"{num(j.get('fiber', 0))}, {arr(a.strip() for a in r[H['Allergens']].split(','))}, "
        f"{'false' if r[H['Diet']] == 'NV' else 'true'}, {'true' if code == 'NVE' else 'false'}, {q(j.get('image'))}, {q(meta)}::jsonb)")
    cost_vals.append(f"  ({q(code)}, {num(r[H['Procurement cost (₹)']])}, {num(r[H['Gas cost (₹)']])})")

sql += [
    "-- Dishes (workbook › Catalog). Existing description/image are kept if already set in admin.",
    "insert into public.menu_items (code, category, name, description, grams, cooked_state, calories, protein, carbs, fat, fiber, allergens, is_veg, contains_egg, image_url, metadata)",
    "select code, category::public.menu_category, name, description, grams, cooked_state, calories, protein, carbs, fat, fiber, allergens, is_veg, contains_egg, image_url, metadata from (values",
    ",\n".join(item_vals),
    ") v(code, category, name, description, grams, cooked_state, calories, protein, carbs, fat, fiber, allergens, is_veg, contains_egg, image_url, metadata)",
    "on conflict (code) do update set category = excluded.category, name = excluded.name,",
    "  description = coalesce(public.menu_items.description, excluded.description), grams = excluded.grams,",
    "  cooked_state = excluded.cooked_state, calories = excluded.calories, protein = excluded.protein, carbs = excluded.carbs,",
    "  fat = excluded.fat, fiber = excluded.fiber, allergens = excluded.allergens, is_veg = excluded.is_veg,",
    "  contains_egg = excluded.contains_egg, image_url = coalesce(public.menu_items.image_url, excluded.image_url),",
    "  metadata = public.menu_items.metadata || excluded.metadata;",
    "",
    "-- Dish costs per portion (workbook › Catalog: procurement + gas). Staff-only table.",
    "insert into public.menu_item_costs (menu_item_id, cost_per_portion, gas_cost)",
    "select mi.id, v.cost, v.gas from (values",
    ",\n".join(cost_vals),
    ") v(code, cost, gas) join public.menu_items mi on mi.code = v.code",
    "on conflict (menu_item_id) do update set cost_per_portion = excluded.cost_per_portion, gas_cost = excluded.gas_cost;",
    "",
]

# --------------------------------------------------------------------------- 30-day rotation
def menu(name):
    m = rows(name)
    hh = {h: i for i, h in enumerate(m[2])}
    days = [{'day': int(r[0]), 'main': r[hh['Main code']], 'ps': r[hh['Protein-side code']],
             'lg': r[hh['Legume code']], 'sl': r[hh['Salad code']], 'cb': r[hh['Carb code']]}
            for r in m[3:] if r and re.fullmatch(r'\d+', r[0])]
    assert len(days) == 30, (name, len(days))
    return days


rot_vals = []
for sheet, diet in (('Menu_NonVeg.csv', 'non_veg'), ('Menu_Veg.csv', 'veg')):
    for d in menu(sheet):
        dinner = dict(d, sl=SALADS[(SALADS.index(d['sl']) + 2) % 6],
                      lg=LEGUMES[(LEGUMES.index(d['lg']) + 3) % 6],
                      cb=CARBS[(CARBS.index(d['cb']) + 3) % 5])
        for slot, x in (('lunch', d), ('dinner', dinner)):
            title = 'Day %d: %s Box' % (x['day'], names[x['main']])
            rot_vals.append(f"  ({x['day']}, '{diet}', '{slot}', {q(title)}, "
                            f"{q(x['main'])}, {q(x['ps'])}, {q(x['sl'])}, {q(x['lg'])}, {q(x['cb'])})")

sql += [
    "-- 30-day rotation (workbook › Menu NonVeg / Menu Veg). Lunch = the workbook's box.",
    "-- Dinner (2-meal plans) = same main + protein side, with salad +2, legume +3, carb +3",
    "-- in catalog order (the rule the website uses today). Change it in admin once decided.",
    "insert into public.menu_rotation (day_number, diet, slot, name, main_id, protein_side_id, salad_id, legume_id, carb_id)",
    "select v.day, v.diet::public.diet_type, v.slot::public.meal_slot, v.name, m.id, ps.id, sl.id, lg.id, cb.id from (values",
    ",\n".join(rot_vals),
    ") v(day, diet, slot, name, main, ps, sl, lg, cb)",
    "join public.menu_items m on m.code = v.main join public.menu_items ps on ps.code = v.ps",
    "join public.menu_items sl on sl.code = v.sl join public.menu_items lg on lg.code = v.lg",
    "join public.menu_items cb on cb.code = v.cb",
    "on conflict (kitchen_id, day_number, diet, slot) do update set name = excluded.name, main_id = excluded.main_id,",
    "  protein_side_id = excluded.protein_side_id, salad_id = excluded.salad_id, legume_id = excluded.legume_id, carb_id = excluded.carb_id;",
    "",
]

# --------------------------------------------------------------------------- Settings
st = rows('Settings.csv')
prices = {r[0]: (r[1], r[2]) for r in st if r and r[0] in ('Daily trial', 'Weekly', 'Monthly')}
dip_price = next(r[1] for r in st if r and r[0] == 'Dip add-on price')

price_vals = []
for plan, key in (('trial', 'Daily trial'), ('weekly', 'Weekly'), ('monthly', 'Monthly')):
    nv, v = prices[key]
    price_vals += [f"  ('{plan}', 'non_veg', {nv})", f"  ('{plan}', 'veg', {v})"]
sql += [
    "-- Price per box (workbook › Settings). Second-meal discount ₹10 kept from the website.",
    "insert into public.pricing_rules (plan_type, diet, price_per_meal, second_meal_discount, effective_from)",
    "select v.plan::public.plan_type, v.diet::public.diet_type, v.price, 10, '2026-01-01' from (values",
    ",\n".join(price_vals),
    ") v(plan, diet, price)",
    "where not exists (select 1 from public.pricing_rules p where p.plan_type = v.plan::public.plan_type",
    "                  and p.diet = v.diet::public.diet_type and p.price_per_meal = v.price);",
    "",
]

cost, section = {}, None
for r in st:
    if not r or not r[0]:
        continue
    if r[0] in ('Cost input', 'Packaging per box', 'Raw material'):
        section = r[0]
        continue
    if len(r) > 1 and re.fullmatch(r'-?\d+(\.\d+)?', r[1] or ''):
        if section == 'Cost input':
            cost[r[0]] = float(r[1])
        elif section == 'Packaging per box':
            cost.setdefault('packaging', {})[r[0]] = float(r[1])
        elif section == 'Raw material':
            cost.setdefault('raw_material_prices', {})[r[0]] = float(r[1])
sql += [
    "-- Cost model (workbook › Settings) for admin analytics. Staff-only (is_public = false).",
    f"insert into public.site_settings (key, value, is_public) values ('cost_model', {q(json.dumps(cost, ensure_ascii=False))}::jsonb, false)",
    "on conflict (key) do update set value = excluded.value;",
    "",
]

# --------------------------------------------------------------------------- Add-ons
addon_vals = []
for i, r in enumerate(dips):
    slug = 'dip-' + re.sub(r'[^a-z0-9]+', '-', r[H['Item']].lower()).strip('-')
    addon_vals.append(
        f"  ('side', {q(slug)}, {q(r[H['Item']])}, {q(r[H['Portion']] + ' dip, optional extra')}, {dip_price}, "
        f"{num(r[H['Calories (kcal)']])}, {num(r[H['Protein (g)']])}, {num(r[H['Carbs (g)']])}, {num(r[H['Fat (g)']])}, null::numeric, null::int, true, "
        f"{arr(['Dip'] + [a.strip() for a in r[H['Allergens']].split(',')])}, null, {100 + i})")
for i, s in enumerate(jdata('sides.json')):
    addon_vals.append(
        f"  ('side', {q(s['slug'])}, {q(s['name'])}, {q(s['description'])}, {s['price']}, {s['calories']}, {s['protein']}, {s['carbs']}, {s['fat']}, "
        f"null, null, {'true' if s['isVeg'] else 'false'}, {arr(s.get('tags', []))}, {q(s.get('image'))}, {i})")
for i, d in enumerate(jdata('addons.json')):
    ml = re.match(r'(\d+)', d.get('volume') or '')
    addon_vals.append(
        f"  ('drink', {q(d['id'])}, {q(d['name'])}, {q(d['description'])}, {d['price']}, {d['calories']}, {d['protein']}, {d['carbs']}, 0, "
        f"{d.get('sugarGrams', 'null')}, {ml.group(1) if ml else 'null'}, true, {arr(d.get('tags', []))}, {q(d.get('image'))}, {50 + i})")
sql += [
    "-- Add-ons: dips at ₹" + dip_price + " (workbook), sides + drinks (data/sides.json, data/addons.json)",
    "insert into public.addons (type, slug, name, description, price, calories, protein, carbs, fat, sugar_g, volume_ml, is_veg, tags, image_url, sort_order)",
    "select type::public.addon_type, slug, name, description, price, calories, protein, carbs, fat, sugar_g, volume_ml, is_veg, tags, image_url, sort_order from (values",
    ",\n".join(addon_vals),
    ") v(type, slug, name, description, price, calories, protein, carbs, fat, sugar_g, volume_ml, is_veg, tags, image_url, sort_order)",
    "on conflict (slug) do nothing;",
    "",
]

# --------------------------------------------------------------------------- Plans
plans = [dict(slug='daily-trial', name='Daily Trial', type='trial', mpd=1, days=1,
              tagline='Try one box for a single day.',
              description='Single-day prepaid order. A first taste of BroTin Box.',
              features=[], ideal_for=[], badge=None, popular=False)]
for p in jdata('plans.json'):
    typ = 'monthly' if 'monthly' in p['slug'] else 'weekly'
    plans.append(dict(slug=p['slug'], name=p['name'], type=typ, mpd=p['mealsPerDay'], days=24 if typ == 'monthly' else 6,
                      tagline=p.get('tagline'), description=p.get('description'), features=p.get('features', []),
                      ideal_for=p.get('idealFor', []), badge=p.get('badge'), popular=p.get('isPopular', False)))
plan_vals = [
    f"  ({q(p['slug'])}, {q(p['name'])}, '{p['type']}', {p['mpd']}, {p['days']}, {q(p['tagline'])}, {q(p['description'])}, "
    f"{q(json.dumps(p['features'], ensure_ascii=False))}::jsonb, {q(json.dumps(p['ideal_for'], ensure_ascii=False))}::jsonb, "
    f"{q(p['badge'])}, {'true' if p['popular'] else 'false'}, {i})"
    for i, p in enumerate(plans)]
sql += [
    "-- Plans (data/plans.json + a 1-day trial). Weekly = 6 operating days, monthly = 24.",
    "insert into public.plans (slug, name, type, meals_per_day, operating_days, tagline, description, features, ideal_for, badge, is_popular, sort_order)",
    "select slug, name, type::public.plan_type, mpd, days, tagline, description, features, ideal_for, badge, popular, sort from (values",
    ",\n".join(plan_vals),
    ") v(slug, name, type, mpd, days, tagline, description, features, ideal_for, badge, popular, sort)",
    "on conflict (slug) do nothing;",
    "",
]

# --------------------------------------------------------------------------- Zones, coupons, FAQs
zone_vals = [
    f"  ({q(z['pincode'])}, {q(z['area'])}, '{z['tier']}', {z.get('deliveryFee', 0)}, {z.get('distanceKm', 'null')}, "
    f"{z.get('avgDeliveryMinutes', 'null')}, {arr(z.get('slots', []))}, {q(z.get('description'))})"
    for z in jdata('delivery-zones.json') if z.get('isDeliverable') and z.get('tier') in ('core', 'phase2')]
sql += [
    "-- Delivery zones (data/delivery-zones.json, deliverable pincodes only)",
    "insert into public.delivery_zones (pincode, area, tier, delivery_fee, distance_km, avg_minutes, slots, description)",
    "select pincode, area, tier::public.zone_tier, fee, km, mins, slots, description from (values",
    ",\n".join(zone_vals),
    ") v(pincode, area, tier, fee, km, mins, slots, description)",
    "on conflict (pincode, area) do nothing;",
    "",
]
coupon_vals = [
    f"  ({q(c['code'])}, {q(c['description'])}, '{c['discountType']}', {c['discountValue']}, {c['minOrderValue']}, {c.get('maxDiscount', 'null')})"
    for c in jdata('coupons.json')]
sql += [
    "-- Coupons (data/coupons.json)",
    "insert into public.coupons (code, description, discount_type, value, min_order, max_discount)",
    "select code, description, dtype::public.discount_type, value, min_order, max_discount from (values",
    ",\n".join(coupon_vals),
    ") v(code, description, dtype, value, min_order, max_discount)",
    "on conflict (code) do nothing;",
    "",
]
faq_vals = [f"  ({q(f['question'])}, {q(f['answer'])}, {i})" for i, f in enumerate(jdata('faqs.json'))]
sql += [
    "-- FAQs (data/faqs.json)",
    "insert into public.faqs (question, answer, sort_order)",
    "select v.question, v.answer, v.sort from (values",
    ",\n".join(faq_vals),
    ") v(question, answer, sort)",
    "where not exists (select 1 from public.faqs f where f.question = v.question);",
    "",
]

with open(out, 'w') as f:
    f.write('\n'.join(sql) + '\n')
print(f'wrote {out}: {len(dishes)} dishes, {len(dips)} dips, {len(rot_vals)} rotation rows, '
      f'prices {prices}, {len(plans)} plans, {len(zone_vals)} zones')
